if (new Set(entries.map(([name]) => name)).size !== entries.length) {
    throw new Error('Additional tool risk catalog contains duplicate names');
}

export const ADDITIONAL_TOOL_RISK_CATALOG: Record<string, ToolRiskMetadata> = Object.fromEntries(entries);
